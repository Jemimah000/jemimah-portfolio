const MAX_PROVIDER_ATTEMPT_MS = 10000;

function getStatus(error) {
  const rawStatus = error?.status ?? error?.statusCode;
  const statusName = String(rawStatus || "").toUpperCase();
  const namedStatus = {
    RESOURCE_EXHAUSTED: 429,
    UNAUTHENTICATED: 401,
    PERMISSION_DENIED: 403,
  }[statusName];
  const status = Number(rawStatus ?? namedStatus);
  return Number.isFinite(status) && status > 0 ? status : null;
}

function getFailureSummary(error) {
  const status = getStatus(error);
  const code = String(error?.code || "").toLowerCase();
  const message = String(error?.message || "").toLowerCase();

  if (status === 401) return "authentication rejected";
  if (status === 403) return "provider access denied";
  if (status === 429 || message.includes("resource_exhausted")) {
    return "quota or rate limit reached";
  }
  if (status === 408 || status === 504 || code.includes("timeout")) {
    return "request timed out";
  }
  if (status >= 500) return "provider server error";
  if (code.includes("econn") || code.includes("network")) {
    return "provider network unavailable";
  }
  return "provider request failed";
}

function getSanitizedErrorMessage(error) {
  let body = error?.error ?? error?.response?.data ?? error?.body;

  if (typeof body === "string") {
    try {
      body = JSON.parse(body);
    } catch {
      body = { message: body };
    }
  }

  const message = [
    body?.error?.message,
    body?.message,
    body?.detail,
    error?.message,
  ].find((value) => typeof value === "string" && value.trim());

  return String(message || "no response message")
    .replace(/[\r\n\t]+/g, " ")
    .replace(/\bBearer\s+[^\s"'`,}]+/gi, "Bearer [REDACTED]")
    .replace(/\b(?:gsk_[A-Za-z0-9_-]+|AIza[A-Za-z0-9_-]+|AQ\.[A-Za-z0-9_-]+)\b/g, "[REDACTED]")
    .replace(/((?:api[_ -]?key|authorization|token)\s*[:=]\s*)("[^"]*"|'[^']*'|[^\s,;]+)/gi, "$1[REDACTED]")
    .slice(0, 240);
}

function isAuthenticationFailure(error) {
  const status = getStatus(error);
  return status === 401 || status === 403;
}

function isQuotaFailure(error) {
  return (
    getStatus(error) === 429 ||
    [error?.message, error?.code, error?.status]
      .some((value) => String(value || "").toLowerCase().includes("resource_exhausted"))
  );
}

function withAttemptTimeout(generate, timeoutMs) {
  const controller = new AbortController();
  let timer;

  const timeout = new Promise((_, reject) => {
    timer = setTimeout(() => {
      controller.abort();
      const error = new Error("Provider request timed out");
      error.code = "ETIMEDOUT";
      reject(error);
    }, timeoutMs);
  });

  return Promise.race([
    Promise.resolve().then(() => generate(controller.signal)),
    timeout,
  ]).finally(() => clearTimeout(timer));
}

export async function generateWithFallback({
  geminiModels,
  groqModel,
  hasGemini,
  hasGroq,
  generateGemini,
  generateGroq,
  deadlineMs = 17000,
  now = Date.now,
  log = console.warn,
}) {
  const deadline = now() + deadlineMs;
  const uniqueGeminiModels = [...new Set(geminiModels || [])];
  const candidates = [];

  if (hasGemini) {
    candidates.push(
      ...uniqueGeminiModels.map((model) => ({
        provider: "Gemini",
        model,
        generate: generateGemini,
      }))
    );
  }

  const firstGemini = candidates.shift();
  const orderedCandidates = [
    ...(firstGemini ? [firstGemini] : []),
    ...(hasGroq
      ? [{ provider: "Groq", model: groqModel, generate: generateGroq }]
      : []),
    ...candidates,
  ];

  let geminiUnavailable = false;
  let geminiQuotaExhausted = false;

  for (const candidate of orderedCandidates) {
    if (
      candidate.provider === "Gemini" &&
      (geminiUnavailable || geminiQuotaExhausted)
    ) {
      continue;
    }

    const remainingMs = deadline - now();
    if (remainingMs <= 0) break;

    const timeoutMs = Math.min(MAX_PROVIDER_ATTEMPT_MS, remainingMs);

    try {
      const reply = await withAttemptTimeout(
        (signal) => candidate.generate({
          model: candidate.model,
          signal,
          timeoutMs,
        }),
        timeoutMs
      );

      if (typeof reply !== "string" || !reply.trim()) {
        throw new Error("Provider returned an empty response");
      }

      console.log(`LUNA reply generated by ${candidate.provider} (${candidate.model})`);
      return {
        reply: reply.trim(),
        model: candidate.model,
        provider: candidate.provider,
      };
    } catch (error) {
      const status = getStatus(error) ?? "n/a";
      log(
        `LUNA provider failure: provider=${candidate.provider} model=${candidate.model} status=${status} reason=${getFailureSummary(error)} message="${getSanitizedErrorMessage(error)}"`
      );

      if (candidate.provider === "Gemini") {
        geminiQuotaExhausted ||= isQuotaFailure(error);
        geminiUnavailable ||= isAuthenticationFailure(error);
      }
    }
  }

  const failure = new Error(
    now() >= deadline
      ? "LUNA provider deadline exceeded"
      : "No configured provider returned a reply"
  );
  failure.code = now() >= deadline ? "LUNA_TIMEOUT" : "LUNA_UNAVAILABLE";
  throw failure;
}